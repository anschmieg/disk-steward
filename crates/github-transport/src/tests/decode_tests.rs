#[test]
fn backward_offset_and_reference_deltas_decode_to_canonical_objects() {
    for pack in [OFS, REF] {
        let report = run(pack, 6).unwrap();
        assert_eq!(report.objects().len(), 2);
        assert_eq!(report.decoded_bytes(), 6);
        assert_eq!(report.checksum().as_slice(), &pack[pack.len() - 20..]);
        for (i, obj) in report.objects().iter().enumerate() {
            assert_eq!(obj.content(), b"x");
            assert_eq!(obj.kind(), GitObjectKind::Blob);
            assert_eq!(obj.delta_depth(), i as u8);
            assert_eq!(obj.oid(), report.objects()[0].oid());
        }
        assert_eq!(report.objects()[0].offset(), 12);
        assert!(report.objects()[1].offset() > 12);
    }
    assert!(run(OFS, 5).is_err()); // Representation fits, reconstruction would exceed cumulative limit.
    assert_eq!(run(EMPTY, 0).unwrap().objects().len(), 0);
}
#[test]
fn chain_depth_and_unavailable_bases_fail_closed() {
    let report = run(CHAIN32, 161).unwrap();
    assert_eq!(report.objects().last().unwrap().delta_depth(), 32);
    assert!(run(CHAIN33, 1024).is_err());
    assert_eq!(
        run(FORWARD, 1024).unwrap_err().kind(),
        ErrorKind::Unsupported
    );
    let mut missing = REF[..REF.len() - 20].to_vec();
    missing[23] ^= 1;
    assert_eq!(
        run(&reseal(missing), 1024).unwrap_err().kind(),
        ErrorKind::Unsupported
    );
    let mut interior = OFS[..OFS.len() - 20].to_vec();
    interior[23] -= 1;
    assert_eq!(
        run(&reseal(interior), 1024).unwrap_err().kind(),
        ErrorKind::Unsupported
    );
}
#[test]
fn checksums_counts_and_exact_body_boundaries_are_required() {
    for count in [0u32, 1, 3, 1025] {
        let mut body = OFS[..OFS.len() - 20].to_vec();
        body[8..12].copy_from_slice(&count.to_be_bytes());
        assert!(run(&reseal(body), 1024).is_err());
    }
    let mut garbage = OFS[..OFS.len() - 20].to_vec();
    garbage.push(0);
    assert!(run(&reseal(garbage), 1024).is_err());
    let mut corrupt = OFS.to_vec();
    *corrupt.last_mut().unwrap() ^= 1;
    assert!(run(&corrupt, 1024).is_err());
    for cut in 0..OFS.len() {
        assert!(run(&OFS[..cut], 1024).is_err());
    }
    let mut zlib = OFS[..OFS.len() - 20].to_vec();
    zlib[13] = 0;
    assert!(run(&reseal(zlib), 1024).is_err());
}
#[test]
fn limits_and_attempt_controls_precede_decode_results() {
    assert_eq!(
        run(EMPTY, 16 * 1024 * 1024 + 1).unwrap_err().kind(),
        ErrorKind::InvalidInput
    );
    assert!(run(&vec![0; 16 * 1024 * 1024 + 1], 1024).is_err());
    let cancel = CancellationHandle::new();
    cancel.cancel();
    assert_eq!(
        decode(EMPTY, 0, &cancel, Instant::now() + Duration::from_secs(1))
            .unwrap_err()
            .kind(),
        ErrorKind::ConnectionAborted
    );
    assert_eq!(
        decode(EMPTY, 0, &CancellationHandle::new(), Instant::now())
            .unwrap_err()
            .kind(),
        ErrorKind::TimedOut
    );
}
